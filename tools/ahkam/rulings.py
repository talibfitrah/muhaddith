def canon(name, book_id=None):
    n = re.sub(r"\s+", " ", name).strip(" :")
    n = re.sub(r"^(?:الشيخ|الإمام)\s+", "", n)
    ctx = BOOK_CTX.get(book_id or "", {})
    if n in ctx:
        return ctx[n]
    if n in CANON:
        return CANON[n]
    # «أبي فلان» → «أبو فلان»
    n2 = re.sub(r"^أبي ", "أبو ", n)
    if n2 in ctx:
        return ctx[n2]
    if n2 in CANON:
        return CANON[n2]
    # اسم غير معروف في القائمة: نقبله إن كان يشبه اسم عالم (نسبة، أو كنية/اسم مركّب) لا ضميرًا ولا كلمة عامة
    if n2 in BAD_NAMES or len(n2) > 40:
        return None
    ws = n2.split(" ")
    if any(w in BAD_TOKENS for w in ws) or any(w.startswith(("بال", "لل", "فو", "وم")) for w in ws[1:]):
        return None
    if len(ws) == 1:
        return n2 if (n2.startswith("ال") and len(n2) > 4) else None
    if ws[0] in ("أبو", "ابن", "أم") or ws[0].startswith("ال") or (len(ws) >= 2 and ws[1] in ("بن", "ابن")) or n2.startswith("عبد "):
        return n2
    return None


SUBJECT_RE = re.compile(r"(?:حديث|الحديث|إسناد|اسناد|خبر|أثر|طريق|رواية|سنده|رواه|أخرجه|روي|يروي|الوجه|المتن|أصل)")
QAL_RE = re.compile(r"(?:قال|قلت|قيل|يقول|قالوا|قالا)")
FILLER = r"(?:\s*(?:هذا|وهذا|هو|وهو|فهو|فهذا|حديث|الحديث|وحديث|إسناده|وإسناده|إسناد|بإسناد|سنده|رجاله|في|هذا|الباب|عندي|عن|أبي|ابن|بن|أبو|و|[ء-ي]{2,12})){0,7}\s*$"

def _speaker_before(before, book_id):
    """يبحث عن «قال فلان :» قبل عبارة الحكم بشرط ألا تفصل بينهما نقطة أو علامة اقتباس."""
    best = None
    # «رواه الحاكم، وقال: صحيح الإسناد» → القائل هو المُخرِّج المذكور
    for rm in RAWAHU_RE.finditer(before):
        gap = before[rm.end():]
        if len(gap) <= 80 and not re.search(r"[.\"»]", gap) and re.fullmatch(FILLER, gap):
            best = rm
    if best is not None:
        return canon(best.group(1), book_id)
    for sm in SPEAKER_RE_ANY.finditer(before):
        gap = before[sm.end():]
        if len(gap) > 80 or re.search(r"[.\"»]", gap):
            continue
        if not re.fullmatch(FILLER, gap):
            continue
        best = sm
    if best is None:
        return None
    return canon(best.group(1), book_id)

RAWAHU_RE = re.compile(r"(?:رواه|أخرجه|ورواه|وأخرجه|وصححه|وحسنه|وضعفه)\s+((?:أبو|أبي|ابن)?\s*[ء-ي]+(?:\s+(?:بن|ابن|أبي|أبو)\s+[ء-ي]+){0,2})\s*[،,]?\s*(?:و|ف)?قال\s*:?")
SPEAKER_RE_ANY = re.compile(SPEAKER_RE.pattern.replace(r"\s*:?\s*$", r"\s*:?"))


def find_rulings(text, book_id=None):
    """يعيد قائمة (عبارة الحكم، المتكلم أو None، بداية، نهاية) من نص خالٍ من التشكيل."""
    out = []
    for pi, pat in enumerate(PATTERNS):
        for m in pat.finditer(text):
            phrase = re.sub(r"[\s،,و]+$", "", m.group(1)).strip(" ،,")
            if len(phrase) < 3:
                continue
            s, e = m.start(1), m.start(1) + len(phrase)
            if any(not (e <= a or s >= b) for _, _, a, b in out):
                continue
            before = text[max(0, s - 90):s]
            if NEG_CONTEXT.search(before.rstrip()):
                continue
            if grade_level(phrase) is None:
                continue
            if pi == 2:
                # الأنماط المجردة: نتأكد أن الكلام عن الحديث لا عن راوٍ
                trig = text[m.start():s].strip()
                if trig.endswith(":") or (m.start() > 0 and text[m.start() - 1] in ":.،,؛"):
                    pre_colon = before.rstrip()[:-1] if before.rstrip().endswith(":") else before
                    qs = list(QAL_RE.finditer(pre_colon[-60:]))
                    if not qs:
                        continue
                    seg = pre_colon[-60:][qs[-1].end():]
                    if len(seg) > 32 or "،" in seg or "," in seg or "." in seg:
                        continue
                elif not SUBJECT_RE.search(before[-70:]):
                    continue
                if re.search(r"(?:بن|ابن|أبو|أبي|مولي|مولى)\s+[ء-ي]+\s*(?:،|,)?\s*(?:وهو|هو|فهو)\s*$", before):
                    continue  # «فلان بن فلان وهو ضعيف» وصف راوٍ
            speaker = _speaker_before(before, book_id)
            if speaker is None:
                far = text[max(0, s - 260):s]
                im = list(re.finditer(r"(?:سألت|وسألت|فسألت|سمعت|وسمعت|سئل|وسئل|فسئل)\s+((?:أبا|أبي|أبو|ابن)?\s*[ء-ي]+(?:\s+بن\s+[ء-ي]+)?)", far))
                if im and not re.search(r"[.\"»]", far[im[-1].end():]):
                    nm = im[-1].group(1).strip()
                    nm = re.sub(r"^أبا ", "أبو ", nm)
                    nm = nm[:-1] if nm.endswith("دا") else nm  # محمدا → محمد
                    speaker = canon(nm, book_id)
            out.append((phrase, speaker, s, e))
    out.sort(key=lambda x: x[2])
    return out


