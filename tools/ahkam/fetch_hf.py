    ap = argparse.ArgumentParser()
    ap.add_argument("--index", required=True); ap.add_argument("--out", required=True); ap.add_argument("--only", default=None)
    ap.add_argument("--list", action="store_true", help="اطبع ما سيُنزَّل فقط")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    picked = pick_rows(a.index)
    total = 0; ok = 0
    for row, prefix, title, author, death, kind in picked:
        if a.only and a.only not in prefix and a.only not in title:
            continue
        paths = ast.literal_eval(row["txt_paths"]) if row["txt_paths"] else []
        print(f"{title} — {author}: {len(paths)} ملفًا ({row['pages']} صفحة)")
        if a.list:
            continue
        for p in sorted(paths):
            name = prefix + "__" + os.path.basename(p)
            dest = os.path.join(a.out, name)
