def pick_rows(index_path):
    rows = list(csv.DictReader(open(index_path, encoding="utf-8"), delimiter="\t"))
    out = []
    for key, prefix, title, author, death, kind in HF_BOOKS:
        hits = [r for r in rows if key in r["title"]]
        if not hits:
            print("!! غير موجود في الفهرس:", key); continue
        hits.sort(key=lambda r: -int(r["pages"] or 0))
        out.append((hits[0], prefix, title, author, death, kind))
    return out


def fetch(url, dest, tries=4):
    for t in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "muhaddith-fetch/1.0"})
            with urllib.request.urlopen(req, timeout=120) as r, open(dest + ".part", "wb") as o:
                while True:
                    b = r.read(1 << 20)
                    if not b: break
                    o.write(b)
            os.replace(dest + ".part", dest); return True
        except Exception as e:
            print(f"   محاولة {t+1} فشلت: {e}")
            time.sleep(3 * (t + 1))
    return False


